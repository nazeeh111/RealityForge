/* Authentic local-app recording. No routes or responses are mocked. */
const fs=require('node:fs');
const path=require('node:path');
const {chromium}=require(process.env.REALITYFORGE_PLAYWRIGHT||'playwright');
const root=path.resolve(__dirname,'..');
const destination=path.resolve(process.env.REALITYFORGE_DEMO_DIR||path.join(root,'docs/assets'));
const scratch=path.resolve(process.env.REALITYFORGE_DEMO_WORK||path.join(root,'.realityforge/demo-recording'));
fs.mkdirSync(destination,{recursive:true});fs.mkdirSync(scratch,{recursive:true});
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.REALITYFORGE_CHROME||undefined,args:['--autoplay-policy=no-user-gesture-required']});
 const context=await browser.newContext({viewport:{width:1440,height:1080},deviceScaleFactor:1,recordVideo:{dir:scratch,size:{width:1440,height:1080}},reducedMotion:'reduce'});
 const page=await context.newPage();const start=Date.now();const events=[];const errors=[];
 const mark=name=>{events.push({name,time_s:(Date.now()-start)/1000});console.log(name,events.at(-1).time_s);};
 page.on('pageerror',error=>errors.push(error.message));
 page.on('response',async response=>{if(response.url().endsWith('/api/analyze')&&response.ok()){const result=await response.json();events.push({name:'actual_analysis_response',time_s:(Date.now()-start)/1000,metrics:result.metrics,model:result.model,training:result.provenance.training});}});
 await page.goto(process.env.REALITYFORGE_URL||'http://127.0.0.1:8001');
 await page.locator('#sampleSelect').selectOption('generated-pendulum');
 await page.locator('#sourceVideo').evaluate(v=>v.readyState>=2?true:new Promise(r=>v.addEventListener('loadeddata',r,{once:true})));
 mark('generated_fixture_loaded');await page.waitForTimeout(1500);
 await page.locator('#analyzeButton').click();mark('recovery_requested');
 await page.waitForFunction(()=>document.getElementById('status').textContent.startsWith('Recovered '),undefined,{timeout:120000});
 mark('recovery_completed');await page.waitForTimeout(1800);
 await page.locator('#playButton').click();mark('observation_and_forecast_playback');await page.waitForTimeout(6200);
 await page.locator('#parameters input[type=number]').first().fill('12');
 await page.waitForFunction(()=>document.getElementById('status').textContent.startsWith('Counterfactual ready'),undefined,{timeout:30000});
 mark('real_counterfactual_ready');await page.locator('#playButton').click();await page.waitForTimeout(6200);
 await page.locator('#scrubber').evaluate(el=>{el.value='780';el.dispatchEvent(new Event('input',{bubbles:true}));});
 await page.waitForTimeout(800);mark('heldout_comparison');
 await page.screenshot({path:path.join(destination,'realityforge-workbench.png'),fullPage:true});
 await page.screenshot({path:path.join(destination,'realityforge-demo-still.png')});
 await page.waitForTimeout(2000);
 const dl=page.waitForEvent('download');await page.locator('#exportLink').click();const download=await dl;
 await download.saveAs(path.join(scratch,'actual-analysis-export.json'));mark('analysis_exported');
 await page.waitForTimeout(1000);
 const video=page.video();await context.close();const videoPath=await video.path();await browser.close();
 const report={source:'Actual local RealityForge UI; original generated fixture; no mocked network responses',events,errors,raw_video:videoPath};
 fs.writeFileSync(path.join(scratch,'recording.json'),JSON.stringify(report,null,2)+'\n');
 fs.writeFileSync(path.join(destination,'demo-provenance.json'),JSON.stringify({...report,raw_video:path.basename(videoPath)},null,2)+'\n');
 if(errors.length)throw Error(errors.join('\n'));
 console.log(JSON.stringify({raw_video:videoPath,report:path.join(scratch,'recording.json')}));
})().catch(error=>{console.error(error);process.exit(1)});
